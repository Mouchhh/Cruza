import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {PGlite}=await import(process.env.PGLITE_MODULE||'@electric-sql/pglite');
const sql=await readFile(new URL('../supabase/multi-clubs/001-base-commune.sql',import.meta.url),'utf8');
const db=new PGlite();
const A='10000000-0000-4000-8000-000000000001', B='20000000-0000-4000-8000-000000000001';
const ALICE='30000000-0000-4000-8000-000000000001', BOB='40000000-0000-4000-8000-000000000001', EVE='50000000-0000-4000-8000-000000000001';
const team='60000000-0000-4000-8000-000000000001';
await db.exec(`create role anon nologin;create role authenticated nologin;create schema auth;create schema storage;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table storage.buckets(id text primary key,name text not null,public boolean not null);
create table storage.objects(bucket_id text not null references storage.buckets(id),name text not null,primary key(bucket_id,name));
alter table storage.objects enable row level security;
grant usage on schema auth,storage to anon,authenticated;
grant select,insert,update,delete on storage.objects to anon,authenticated;`);
await db.exec(sql);
await db.exec(`insert into auth.users values ('${ALICE}'), ('${BOB}'), ('${EVE}');
insert into cruza_clubs(id,slug,name) values ('${A}','club-a','Club A'), ('${B}','club-b','Club B');
insert into cruza_memberships values ('${A}','${ALICE}','educateur',true), ('${B}','${BOB}','responsable',true), ('${A}','${EVE}','responsable',true), ('${B}','${EVE}','educateur',true);
insert into cruza_teams(club_id,id,name) values ('${B}','${team}','U17');
insert into cruza_documents(club_id,owner_id,kind,title,payload,shared) values
 ('${A}','${ALICE}','seance','Séance A','{}',true), ('${A}','${ALICE}','photo','Photo A','{}',false), ('${B}','${BOB}','seance','Séance B','{}',true);
insert into storage.objects values ('cruza-club-private','${A}/${ALICE}/a.jpg'), ('cruza-club-private','${B}/${BOB}/b.jpg');`);
async function as(user) {
  await db.exec('reset role; set role authenticated');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[user]);
}
const list=async query=>(await db.query(query)).rows;
await as(ALICE);
assert.deepEqual(await list('select slug from cruza_clubs'),[{slug:'club-a'}]);
assert.deepEqual(await list('select title from cruza_documents order by title'),[{title:'Photo A'},{title:'Séance A'}]);
assert.deepEqual(await list('select name from storage.objects'),[{name:`${A}/${ALICE}/a.jpg`}]);
assert.deepEqual(await list('select name from cruza_teams'),[]);
await assert.rejects(db.query("insert into cruza_documents(club_id,kind,title,payload) values ($1,'bilan','Intrus','{}')",[B]),{code:'42501'});
assert.equal((await db.query("insert into cruza_documents(club_id,kind,title,payload) values ($1,'bilan','Brouillon A','{}')",[A])).affectedRows,1);
assert.equal((await db.query("update cruza_documents set title='Brouillon mis à jour' where title='Brouillon A'")).affectedRows,1);
assert.equal((await db.query("delete from cruza_documents where title='Brouillon mis à jour'")).affectedRows,1);
await assert.rejects(db.query("update cruza_documents set shared=true where title='Photo A'"),{code:'23514'});
await assert.rejects(db.query("insert into cruza_documents(club_id,team_id,kind,title,payload) values ($1,$2,'bilan','Équipe étrangère','{}')",[A,team]),{code:'23503'});
await assert.rejects(db.query('update cruza_documents set club_id=$1',[B]),{code:'42501'});
await assert.rejects(db.query("insert into storage.objects values ('cruza-club-private',$1)",[`${B}/${ALICE}/intrus.jpg`]),{code:'42501'});
await as(BOB);
assert.deepEqual(await list('select title from cruza_documents'),[{title:'Séance B'}]);
assert.equal((await db.query("delete from cruza_documents where title='Séance A'")).affectedRows,0);
await as(EVE);
assert.deepEqual(await list('select slug from cruza_clubs order by slug'),[{slug:'club-a'},{slug:'club-b'}]);
assert.deepEqual(await list('select title from cruza_documents order by title'),[{title:'Séance A'},{title:'Séance B'}]);
assert.deepEqual(await list('select name from storage.objects'),[]);
assert.equal((await db.query("update cruza_documents set title='Modifié' where title='Séance A'")).affectedRows,0);
await db.exec(`reset role; update cruza_memberships set active=false where user_id='${ALICE}';`);
await as(ALICE);
assert.deepEqual(await list('select slug from cruza_clubs'),[]);
assert.deepEqual(await list('select title from cruza_documents'),[]);
assert.deepEqual(await list('select name from storage.objects'),[]);
await db.exec("reset role; set role anon; select set_config('request.jwt.claim.sub','',false);");
await assert.rejects(db.query('select * from cruza_documents'),{code:'42501'});
assert.deepEqual(await list('select name from storage.objects'),[]);
await db.exec('reset role');
await db.close();
